// Compiles the MJML email sources in supabase/emails into one TypeScript module that the Edge
// Functions import (functions cannot read loose files reliably). Re-run after editing a template:
//   npm run build:emails
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import mjml from 'mjml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'supabase/emails');
const out = path.join(root, 'supabase/functions/_shared/emailTemplates.generated.ts');

const templates = {};
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.mjml')).sort()) {
  const source = readFileSync(path.join(srcDir, file), 'utf8');
  const { html, errors } = await mjml(source, { validationLevel: 'strict' });
  if (errors?.length) throw new Error(`${file}: ${errors.map((e) => e.formattedMessage).join('; ')}`);
  const subject = /<mj-title>([\s\S]*?)<\/mj-title>/.exec(source)?.[1].trim() || 'Airport Assist Ghana';
  templates[file.replace(/\.mjml$/, '')] = { subject, html };
}

writeFileSync(
  out,
  `// GENERATED by scripts/build-emails.mjs from supabase/emails/*.mjml. Do not edit by hand.\n` +
    `export const EMAIL_TEMPLATES: Record<string, { subject: string; html: string }> = ${JSON.stringify(templates, null, 2)};\n`,
);
console.log(`Built ${Object.keys(templates).length} email templates -> ${path.relative(root, out)}`);
